class CharChatTokenizer:
    eos_token_id = 1

    def encode(self, text, add_special_tokens=False):
        return [ord(c) for c in text]

    def decode(self, ids, skip_special_tokens=False):
        return "".join(chr(i) for i in ids)

    def apply_chat_template(self, messages, tokenize=True, add_generation_prompt=True):
        return [ord(c) for c in "<" + messages[0]["content"] + ">"]


def test_rows_carry_both_orders_and_the_blocked_spans(fresh_setup):
    plan, _ = fresh_setup
    groups, _ = occ.fresh_groups(plan, count=4)
    tok = CharChatTokenizer()
    rows = occ.fresh_rows(groups, tok)
    assert len(rows) == 16 and any(occ.main_stratum(r) for r in rows)
    for row in rows:
        after, first = (tok.decode(row[o]["input_ids"]) for o in ("after", "first"))
        assert after.startswith("<x =") or after.startswith("<y =")
        assert first.startswith("<What is " + row["variable"] + "?")
        other = "y" if row["variable"] == "x" else "x"
        blocked = "".join(first[t] for t in row["first"]["block_other"])
        assert blocked and all(line.startswith(other + " =") for line in blocked.strip("\n").split("\n"))
        assert tok.decode(row["first"]["sequence"]["targets"]) == row["answer"]


def test_evaluate_row_runs_every_condition(model_factory):
    from test_answer_knockout import _eager

    model = _eager(model_factory(layers=3))
    seq = {"ids": [5, 6, 7, 8, 9, 10, 11, 12], "positions": [7], "targets": [13]}
    row = {"id": "r", "after": {"span": [1, 4], "sequence": seq},
           "first": {"span": [1, 4], "sequence": seq, "before_last_line": [1, 2], "block_other": [3],
                     "other_sequence": {**seq, "targets": [14]}}}
    out = occ.evaluate_row(model, row, 2, "cpu")
    assert set(out["after"]) == {"baseline"}
    assert set(out["first"]) == {*occ.FIRST_CONDITIONS, "baseline_says_other", "block_other_says_other"}
    assert out["first"]["late"]["logprob"] != out["first"]["floor"]["logprob"]  # from layer 2 of 3, not 0
    assert out["after"]["baseline"] == out["first"]["baseline"]


def _ok(correct):
    return {"correct": correct, "logprob": -1.0}


def _fake_run(tmp_path, family, outcome, groups=120, inventory="inv"):
    """outcome(g, k) -> (after baseline, first baseline, block_other, only_last_line, floor, late) for prompt k of group g."""
    run = tmp_path / family
    run.mkdir()
    stimuli, results = [], []
    for g in range(groups):
        for k in range(4):
            sid = f"test_fifth-{g:04d}-{'AABB'[k]}-{'xy'[k % 2]}"
            stimuli.append({"id": sid, "group_id": f"test_fifth-{g:04d}", "last_line_assigns_asked": k % 2 == 0,
                            "depends_on_other": False})
            a, b, o, s, f, late = outcome(g, k)
            results.append({"id": sid, "after": {"baseline": _ok(a)},
                            "first": {"baseline": _ok(b), "block_other": _ok(o), "only_last_line": _ok(s), "floor": _ok(f), "late": _ok(late)}})
    (run / "stimuli.json").write_text(json.dumps(stimuli))
    (run / "results.jsonl").write_text("".join(json.dumps(r) + "\n" for r in results))
    (run / "manifest.json").write_text(json.dumps({"family": family, "prompts": len(results), "plan_hash": occ.PLAN_HASH,
                                                   "protocol_sha256": occ.sha256_file(occ.PROTOCOL),
                                                   "stimuli_sha256": occ.sha256_file(run / "stimuli.json"),
                                                   "generation": {"inventory_sha256": inventory}}))
    (run / "completion.json").write_text(json.dumps({"status": "COMPLETE"}))
    return run


def test_verdicts_follow_the_frozen_rules(tmp_path, monkeypatch):
    monkeypatch.setattr(occ, "RESAMPLES", 2000)
    # Gemma: block_other restores everything; first-order baseline fails half of the main prompts; late always fails.
    gemma = _fake_run(tmp_path, "gemma3-12b", lambda g, k: (True, g % 2 == 0 or k % 2 == 0, True, False, False, False))
    # Qwen: block_other never helps (residual gap 1 on main prompts), the last line suffices (summary 1), late never fails.
    qwen = _fake_run(tmp_path, "qwen2.5-7b", lambda g, k: (True, True, k % 2 == 0, True, False, True))
    result = occ.evaluate([gemma, qwen])
    status = {h["id"]: h["status"] for h in result["hypotheses"]}
    assert status == {"G1": "SUPPORTED", "G2": "SUPPORTED", "G3": "SUPPORTED", "G4": "SUPPORTED",
                      "Q1": "NOT_SUPPORTED", "Q2": "NOT_SUPPORTED", "Q3": "NOT_SUPPORTED", "Q4": "SUPPORTED"}
    by_id = {h["id"]: h for h in result["hypotheses"]}
    assert by_id["G2"]["mean"] == pytest.approx(0.5) and by_id["G2"]["prompts"] == 240 and by_id["G4"]["prompts"] == 480
    assert result["families"]["qwen2.5-7b"]["describe"]["main"]["first_block_other"] == 0.0


def test_families_must_share_the_same_fresh_programs(tmp_path):
    a = _fake_run(tmp_path, "gemma3-12b", lambda g, k: (True,) * 6, inventory="one")
    b = _fake_run(tmp_path, "qwen2.5-7b", lambda g, k: (True,) * 6, inventory="two")
    with pytest.raises(ValueError, match="different fresh programs"):
        occ.evaluate([a, b])


