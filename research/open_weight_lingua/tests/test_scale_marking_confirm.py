def test_fresh_groups_exclude_every_earlier_program(fresh_setup):
    plan, earlier = fresh_setup
    groups, _ = rcf.fresh_groups(plan, count=5)
    old = {tasks.canonical(p) for split in SPLIT_ORDER for g in plan.groups[split] for p in (g.source, g.counterfactual)}
    old |= {tasks.canonical(p) for gs, _ in earlier for g in gs for p in (g.source, g.counterfactual)}
    assert len(groups) == 5 and not {tasks.canonical(p) for g in groups for p in (g.source, g.counterfactual)} & old


