def _stand_in(plan, monkeypatch, name, seed, count=3):
    monkeypatch.setitem(tasks.SPLIT_SEEDS, name, seed)
    excluded = {tasks.canonical(p) for split in SPLIT_ORDER for g in plan.groups[split] for p in (g.source, g.counterfactual)}
    return tasks.generate_groups(name, count, excluded_programs=excluded)


@pytest.fixture
def fresh_setup(monkeypatch):
    """Test-only seeds everywhere: the real ninth split is first generated by the frozen run."""
    plan = _tiny_plan()
    earlier = [_stand_in(plan, monkeypatch, f"test_earlier_{i}", 999070 + i) for i in range(8)]
    monkeypatch.setitem(tasks.SPLIT_SEEDS, "test_ninth", 999079)
    monkeypatch.setattr(rcf, "SPLIT", "test_ninth")
    monkeypatch.setattr(rcf, "PLAN_HASH", plan.plan_hash)
    for name, stand_in in zip(GENERATORS, earlier):
        monkeypatch.setattr(rcf, name, lambda p, s=stand_in: s)
    monkeypatch.setattr(rcf, "FRESH_INVENTORIES", {n: e[1]["inventory_sha256"] for n, e in zip(EARLIER, earlier)})
    return plan, earlier


