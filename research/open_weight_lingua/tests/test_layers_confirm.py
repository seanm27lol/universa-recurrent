class CharChatTokenizer:
    eos_token_id = 1

    def encode(self, text, add_special_tokens=False):
        return [ord(c) for c in text]

    def decode(self, ids, skip_special_tokens=False):
        return "".join(chr(i) for i in ids)

    def apply_chat_template(self, messages, tokenize=True, add_generation_prompt=True):
        return [ord(c) for c in "<" + messages[0]["content"] + ">"]


def test_rows_keep_only_prompts_where_the_mark_decides(fresh_setup, monkeypatch):
    from open_weight_lingua import question_route_knockout as qrk

    # Character tokens put a `y` inside "Reply" and "only"; real tokenizers give " y" its own token.
    monkeypatch.setattr(qrk, "name_token", lambda tok, ids, question, variable: question[0] + len("What is "))
    plan, _ = fresh_setup
    groups, _ = rcf.fresh_groups(plan, count=6)
    rows = rcf.fresh_rows(groups, CharChatTokenizer())
    assert rows and all(not r["last_line_assigns_asked"] and not r["depends_on_other"] and "other" in r["values"] for r in rows)
    assert len(rows) <= 12  # at most one prompt per program


def test_frozen_windows_match_the_protocol():
    assert rcf.conditions("gemma3-12b")["from_24"] == set(range(24, 48))
    assert rcf.conditions("gemma3-12b")["until_12"] == set(range(12))
    assert rcf.conditions("qwen2.5-7b")["from_14"] == set(range(14, 28))
    assert {h[2] for h in rcf.HYPOTHESES} == {c for f in rcf.WINDOWS for c in rcf.WINDOWS[f]}


def _ok(correct):
    return {"correct": correct, "logprob": -1.0}


def _fake_run(tmp_path, family, says, groups=120, inventory="inv"):
    """says(g, condition) -> whether the other value is said on group g's prompts."""
    run = tmp_path / family
    run.mkdir()
    stimuli, results = [], []
    for g in range(groups):
        for side in "AB":
            sid = f"test_eighth-{g:04d}-{side}-x"
            stimuli.append({"id": sid, "group_id": f"test_eighth-{g:04d}"})
            results.append({"id": sid, **{c: {"answer": _ok(not says(g, c)), "other": _ok(says(g, c))} for c in rcf.conditions(family)}})
    (run / "stimuli.json").write_text(json.dumps(stimuli))
    (run / "results.jsonl").write_text("".join(json.dumps(r) + "\n" for r in results))
    (run / "manifest.json").write_text(json.dumps({"family": family, "prompts": len(results), "plan_hash": rcf.PLAN_HASH,
                                                   "protocol_sha256": rcf.sha256_file(rcf.PROTOCOL),
                                                   "stimuli_sha256": rcf.sha256_file(run / "stimuli.json"),
                                                   "generation": {"inventory_sha256": inventory}}))
    (run / "completion.json").write_text(json.dumps({"status": "COMPLETE"}))
    return run


def test_verdicts_follow_the_frozen_rules(tmp_path, monkeypatch):
    monkeypatch.setattr(rcf, "RESAMPLES", 2000)
    # Gemma: the window edges as predicted.
    gemma = _fake_run(tmp_path, "gemma3-12b", lambda g, c: c in ("from_18", "until_12"))
    # Qwen: marking continues past 17, and the early block does nothing.
    qwen = _fake_run(tmp_path, "qwen2.5-7b", lambda g, c: c in ("from_17", "from_14") and g % 2 == 0)
    result = rcf.evaluate([gemma, qwen])
    status = {h["id"]: h["status"] for h in result["hypotheses"]}
    assert status == {"G1": "SUPPORTED", "G2": "SUPPORTED", "G3": "SUPPORTED",
                      "Q1": "NOT_SUPPORTED", "Q2": "SUPPORTED", "Q3": "NOT_SUPPORTED"}
    by_id = {h["id"]: h for h in result["hypotheses"]}
    assert by_id["G2"]["mean"] == pytest.approx(1.0) and by_id["G2"]["units"] == 240 and by_id["Q2"]["mean"] == pytest.approx(0.5)
    assert result["families"]["gemma3-12b"]["rates"]["until_12"]["says_other"] == 1.0


def test_families_must_share_the_same_fresh_programs(tmp_path):
    a = _fake_run(tmp_path, "gemma3-12b", lambda g, c: False, inventory="one")
    b = _fake_run(tmp_path, "qwen2.5-7b", lambda g, c: False, inventory="two")
    with pytest.raises(ValueError, match="different fresh programs"):
        rcf.evaluate([a, b])


def test_run_end_to_end_on_a_fixture_model(tmp_path, monkeypatch, model_factory, tokenizer, fresh_setup):
    """Tiny random model and fixture tokens; plumbing only, never a real result."""
    import transformers

    from test_answer_knockout import _eager

    plan, _ = fresh_setup
    lock = tmp_path / "model-lock-gemma3-12b.json"
    lock.write_text(json.dumps({"models": {"target": {"revision": "r", "files": {}}}}))
    monkeypatch.setattr(rcf, "build_plan", lambda: plan)
    monkeypatch.setattr(rcf, "fresh_groups", lambda p, count=3, real=rcf.fresh_groups: real(p, count))
    seq = lambda item, t: {"ids": list(item["input_ids"]) + [t], "positions": [len(item["input_ids"]) - 1], "targets": [t]}  # noqa: E731
    monkeypatch.setattr(rcf, "route_row", lambda item, split, tok: {
        "id": item["id"], "group_id": item["group_id"], "input_ids": item["input_ids"], "question": [0, 1], "span": [2, 3],
        "values": {"answer": 1, "other": 2}, "last_line_assigns_asked": item["variable"] == "x", "depends_on_other": False,
        "sequences": {"answer": seq(item, 10), "other": seq(item, 11)}})
    monkeypatch.setattr(rcf, "DEPTH", {"gemma3-12b": 3})
    monkeypatch.setattr(rcf, "WINDOWS", {"gemma3-12b": {"from_2": range(2, 3), "until_1": range(0, 1)}})
    monkeypatch.setattr(rcf, "load_model", lambda path, role, device: _eager(model_factory(layers=3)))
    monkeypatch.setattr(rcf, "read_lock", lambda path: json.loads(path.read_text()))
    monkeypatch.setattr(rcf, "model_paths", lambda lock, cache: {"target": tmp_path})
    monkeypatch.setattr(rcf, "verify_models", lambda lock, paths: {})
    monkeypatch.setattr(rcf, "compatibility", lambda device: {})
    monkeypatch.setattr(transformers.AutoTokenizer, "from_pretrained", lambda path, **kwargs: tokenizer)
    run_dir = tmp_path / "confirm"
    rcf.main(["run", "--lock", str(lock), "--device", "cpu", "--run-dir", str(run_dir)])
    completion = json.loads((run_dir / "completion.json").read_text())
    manifest = json.loads((run_dir / "manifest.json").read_text())
    assert completion["status"] == "COMPLETE" and completion["rows_written"] == manifest["prompts"] == 6
    assert manifest["split"] == "test_eighth" and manifest["windows"] == {"from_2": [2, 2], "until_1": [0, 0]}
    first = json.loads((run_dir / "results.jsonl").read_text().splitlines()[0])
    assert set(first) == {"id", "baseline", "from_2", "until_1"}
