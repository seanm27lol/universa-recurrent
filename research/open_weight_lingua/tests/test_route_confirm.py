    plan = _tiny_plan()
    earlier = [_stand_in(plan, monkeypatch, f"test_earlier_{i}", 999040 + i) for i in range(5)]
    monkeypatch.setitem(tasks.SPLIT_SEEDS, "test_sixth", 999046)
    monkeypatch.setattr(rcf, "SPLIT", "test_sixth")
    monkeypatch.setattr(rcf, "PLAN_HASH", plan.plan_hash)
