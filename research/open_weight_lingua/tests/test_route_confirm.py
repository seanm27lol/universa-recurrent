class CharChatTokenizer:
    eos_token_id = 1

    def encode(self, text, add_special_tokens=False):
        return [ord(c) for c in text]

    def decode(self, ids, skip_special_tokens=False):
        return "".join(chr(i) for i in ids)

    def apply_chat_template(self, messages, tokenize=True, add_generation_prompt=True):
        return [ord(c) for c in "<" + messages[0]["content"] + ">"]


def test_rows_locate_the_clause_and_pair_the_strata(fresh_setup, monkeypatch):
    from open_weight_lingua import question_route_knockout as qrk

    # Character tokens put a `y` inside "Reply" and "only"; real tokenizers give " y" its own token.
    monkeypatch.setattr(qrk, "name_token", lambda tok, ids, question, variable: question[0] + len("What is "))
    plan, _ = fresh_setup
    groups, _ = rcf.fresh_groups(plan, count=4)
    tok = CharChatTokenizer()
    rows = rcf.fresh_rows(groups, tok)
    assert len(rows) == 16
    for row in rows:
        text = tok.decode(row["input_ids"])
        assert text[row["clause"][0] : row["clause"][1] + 1] == f"What is {row['variable']}?"
        assert row["question"][0] == row["clause"][0] and row["clause"][1] < row["question"][1]
    fake = [{"baseline": {"answer": {"correct": True}}, "program_blind": {"answer": {"correct": False}}} for _ in rows]
    contrast = rcf.units(rows, fake, "stratum_contrast")
    assert len(contrast) == sum(rcf.main_stratum(r) for r in rows) and all(v == 0 for _, v in contrast)


def test_blocks_follow_the_frozen_table():
    row = {"question": [1, 10], "clause": [1, 4], "span": [12, 20]}
    assert rcf.blocks(row, 25, "baseline") == []
    assert rcf.blocks(row, 25, "program_blind") == [(list(range(12, 21)), list(range(1, 11)))]
    assert rcf.blocks(row, 25, "reader_blind_clause") == [(list(range(21, 25)), [1, 2, 3, 4])]


def _ok(correct):
    return {"correct": correct, "logprob": -1.0}


def _fake_run(tmp_path, family, outcome, groups=120, inventory="inv"):
    """outcome(g, side, asked_last) -> (baseline answer, baseline other, blind answer, blind other)."""
    run = tmp_path / family
    run.mkdir()
    stimuli, results = [], []
    for g in range(groups):
        for side in "AB":
            for asked_last in (True, False):
                sid = f"test_sixth-{g:04d}-{side}-{'xy'[asked_last]}"
                stimuli.append({"id": sid, "group_id": f"test_sixth-{g:04d}", "side": side,
                                "last_line_assigns_asked": asked_last, "depends_on_other": False})
                a, o, ba, bo = outcome(g, side, asked_last)
                said = {"baseline": {"answer": _ok(a), "other": _ok(o)}, "program_blind": {"answer": _ok(ba), "other": _ok(bo)},
                        "reader_blind_clause": {"answer": _ok(a), "other": _ok(o)}}
                results.append({"id": sid, **said})
    (run / "stimuli.json").write_text(json.dumps(stimuli))
    (run / "results.jsonl").write_text("".join(json.dumps(r) + "\n" for r in results))
    (run / "manifest.json").write_text(json.dumps({"family": family, "prompts": len(results), "plan_hash": rcf.PLAN_HASH,
                                                   "protocol_sha256": rcf.sha256_file(rcf.PROTOCOL),
                                                   "stimuli_sha256": rcf.sha256_file(run / "stimuli.json"),
                                                   "generation": {"inventory_sha256": inventory}}))
    (run / "completion.json").write_text(json.dumps({"status": "COMPLETE"}))
    return run


def test_verdicts_follow_the_frozen_rules(tmp_path, monkeypatch):
    monkeypatch.setattr(rcf, "RESAMPLES", 2000)
    # Gemma: the recency default on every program ending on the other variable.
    gemma = _fake_run(tmp_path, "gemma3-12b", lambda g, side, last: (True, False, last, not last))
    # Qwen: blinding the program hurts both strata alike and never yields the other value.
    qwen = _fake_run(tmp_path, "qwen2.5-7b", lambda g, side, last: (True, False, side == "A", False))
    result = rcf.evaluate([gemma, qwen])
    status = {h["id"]: h["status"] for h in result["hypotheses"]}
    assert status == {"G1": "SUPPORTED", "G2": "SUPPORTED", "G3": "SUPPORTED",
                      "Q1": "NOT_SUPPORTED", "Q2": "SUPPORTED", "Q3": "NOT_SUPPORTED"}
    by_id = {h["id"]: h for h in result["hypotheses"]}
    assert by_id["G3"]["mean"] == pytest.approx(1.0) and by_id["G3"]["units"] == 240 and by_id["Q2"]["mean"] == pytest.approx(0.5)
    assert result["families"]["gemma3-12b"]["describe"]["main"]["program_blind"]["says_other"] == 1.0


def test_families_must_share_the_same_fresh_programs(tmp_path):
    a = _fake_run(tmp_path, "gemma3-12b", lambda g, s, last: (True, False, True, False), inventory="one")
    b = _fake_run(tmp_path, "qwen2.5-7b", lambda g, s, last: (True, False, True, False), inventory="two")
    with pytest.raises(ValueError, match="different fresh programs"):
        rcf.evaluate([a, b])


