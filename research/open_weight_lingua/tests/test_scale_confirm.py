class CharChatTokenizer:
    eos_token_id = 1

    def encode(self, text, add_special_tokens=False):
        return [ord(c) for c in text]

    def decode(self, ids, skip_special_tokens=False):
        return "".join(chr(i) for i in ids)

    def apply_chat_template(self, messages, tokenize=True, add_generation_prompt=True):
        return [ord(c) for c in "<" + messages[0]["content"] + ">"]


def test_routing_uses_only_the_first_groups_and_locates_the_program(fresh_setup, monkeypatch):
    plan, _ = fresh_setup
    monkeypatch.setattr(scc, "ROUTING_GROUPS", 2)
    groups, _ = scc.fresh_groups(plan, count=24)  # enough for some prompts to pass the selection rule
    tok = CharChatTokenizer()
    rows = scc.routing_rows(groups, tok)
    assert len(rows) == 8 and {r["group_id"] for r in rows} == {g.group_id for g in groups[:2]}
    for row in rows:
        first, last = row["span"]
        assert tok.decode(row["input_ids"][first : last + 1]) == program_text(row["prompt"])
        assert tok.decode(row["sequence"]["targets"]) == row["answer"]
    selection = scc.selection_rows(groups, tok)
    assert selection and all(r["source"] == "test_fourth" and len(set(r["values"].values())) == 3 for r in selection)


def test_routing_conditions_block_the_frozen_cells(model_factory, monkeypatch):
    from test_answer_knockout import _eager

    model = _eager(model_factory(layers=3))
    monkeypatch.setattr(scc, "ROUTES", {"answer@0": ("answer", 0), "after_program@2": ("after_program", 2), "late": ("after_program", 3)})
    row = {"id": "r", "span": [1, 4], "sequence": {"ids": [5, 6, 7, 8, 9, 10, 11, 12], "positions": [7], "targets": [13]}}
    out = scc.evaluate_routing(model, row, "cpu")
    assert set(out) == {"baseline", "answer@0", "after_program@2", "late"}
    assert out["late"] == out["baseline"]  # from layer 3 of 3: nothing is blocked
    assert out["answer@0"]["logprob"] != out["baseline"]["logprob"]


def _says(v0, v1, v2):
    return {"v0": {"correct": v0, "logprob": -1.0}, "v1": {"correct": v1, "logprob": -1.0}, "v2": {"correct": v2, "logprob": -1.0}}


def _ok(correct):
    return {"correct": correct, "logprob": -1.0}


def _fake_run(tmp_path, lost, falls_back, previous_hurts, groups=120, family="gemma3-27b"):
    """lost(condition, g, k) says whether a routing knockout breaks prompt k of group g."""
    run = tmp_path / "run"
    run.mkdir()
    stimuli, lines = {"routing": [], "selection": []}, []
    for g in range(groups):
        for k in range(2):
            sid = f"test_fourth-{g:04d}-{'AB'[k]}-x"
            stimuli["routing"].append({"id": sid, "group_id": f"test_fourth-{g:04d}"})
            lines.append({"part": "routing", "id": sid, "baseline": _ok(True),
                          **{c: _ok(not lost(c, g, k)) for c in scc.ROUTES}})
    for g in range(groups):
        sid = f"test_fourth-{g:04d}-A-y"
        stimuli["selection"].append({"id": sid, "group_id": f"test_fourth-{g:04d}"})
        fb = falls_back(g)
        lines.append({"part": "selection", "id": sid, "baseline": _says(True, False, False), "final": _says(not fb, fb, False),
                      "final_and_previous": _says(not fb, False, fb), "previous": _says(not previous_hurts(g), False, False)})
    (run / "stimuli.json").write_text(json.dumps(stimuli))
    (run / "results.jsonl").write_text("".join(json.dumps(r) + "\n" for r in lines))
    (run / "manifest.json").write_text(json.dumps({
        "family": family, "prompts": {"routing": 2 * groups, "selection": groups}, "plan_hash": scc.PLAN_HASH,
        "protocol_sha256": scc.sha256_file(scc.PROTOCOL), "stimuli_sha256": scc.sha256_file(run / "stimuli.json"),
        "generation": {"inventory_sha256": "inv"}}))
    (run / "completion.json").write_text(json.dumps({"status": "COMPLETE"}))
    return run


def test_verdicts_follow_the_frozen_rules(tmp_path, monkeypatch):
    monkeypatch.setattr(scc, "RESAMPLES", 2000)
    # answer@0 never hurts; @46 breaks every other group (loss 0.5); @38 breaks every prompt (loss 1).
    lost = {"answer@0": lambda g, k: False, "after_program@46": lambda g, k: g % 2 == 0, "after_program@38": lambda g, k: True}
    run = _fake_run(tmp_path, lambda c, g, k: lost[c](g, k), lambda g: g % 4 != 0, lambda g: False)
    result = scc.evaluate(run)
    status = {h["id"]: h["status"] for h in result["hypotheses"]}
    assert status == {"R1": "SUPPORTED", "R2": "NOT_SUPPORTED", "R3": "SUPPORTED",
                      "S1": "SUPPORTED", "S2": "SUPPORTED", "S3": "SUPPORTED"}
    by_id = {h["id"]: h for h in result["hypotheses"]}
    assert by_id["R2"]["mean"] == pytest.approx(0.5) and by_id["S1"]["mean"] == pytest.approx(0.75)
    assert by_id["R1"]["prompts"] == 240 and by_id["S1"]["prompts"] == 120
    assert result["routing_accuracy"]["after_program@38"] == 0.0 and result["selection_says"]["final"]["v1"] == pytest.approx(0.75)


def test_another_family_or_a_partial_run_is_refused(tmp_path):
    run = _fake_run(tmp_path, lambda c, g, k: False, lambda g: False, lambda g: False, family="gemma3-12b")
    with pytest.raises(ValueError, match="family, plan or protocol"):
        scc.evaluate(run)
    (run / "completion.json").write_text(json.dumps({"status": "FAILED"}))
    with pytest.raises(ValueError, match="incomplete"):
        scc.evaluate(run)


