def _stand_in(plan, monkeypatch, name, seed, count=3):
    monkeypatch.setitem(tasks.SPLIT_SEEDS, name, seed)
    excluded = {tasks.canonical(p) for split in SPLIT_ORDER for g in plan.groups[split] for p in (g.source, g.counterfactual)}
    return tasks.generate_groups(name, count, excluded_programs=excluded)


